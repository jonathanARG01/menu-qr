// Devuelve el elemento con sus textos en el idioma pedido; lo que no esté traducido queda en español.
export function traducir<T extends { traducciones?: Traducciones }>(item: T, idioma: Idioma, campos: (keyof T & string)[]): T {
  const tr = idioma === "es" ? undefined : item.traducciones?.[idioma];
  if (!tr) return item;
  const copia = { ...item };
  for (const campo of campos) {
    const valor = tr[campo]?.trim();
    if (valor) (copia as Record<string, unknown>)[campo] = valor;
  }
  return copia;
}
