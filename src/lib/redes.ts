// Convierte lo que escribió el restaurante (@usuario, usuario, dominio o enlace) en una dirección segura.
// Devuelve null si no se puede armar un enlace http(s).
export function enlaceRed(red: Red, valor: string): string | null {
  let v = valor.trim();
  if (!v) return null;
  const perfil = INFO_RED[red].perfil;
  const usuario = v.replace(/^@/, "");
  if (perfil && /^[\w.-]+$/.test(usuario) && !/\.(com|cl|net|org)$/i.test(usuario)) return perfil(usuario);
  if (!/^https?:\/\//i.test(v)) v = `https://${v}`;
  try {
    const url = new URL(v);
    return url.protocol === "https:" || url.protocol === "http:" ? url.href : null;
  } catch {
    return null;
  }
}

// Une lo guardado con las redes conocidas (lo que no sea texto se descarta).
export function leerRedes(guardado: unknown): Redes {
  const g = (guardado && typeof guardado === "object" ? guardado : {}) as Record<string, unknown>;
  return Object.fromEntries(REDES.map((r) => [r, typeof g[r] === "string" ? (g[r] as string).slice(0, 200) : ""])) as Redes;
}
